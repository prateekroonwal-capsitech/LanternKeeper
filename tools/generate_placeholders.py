# ── World dressing (Phase 5) ─────────────────────────────────────────────
def dressing() -> None:
    sil = (6, 7, 11, 255)

    def tree(rel, w, h, branches, seed):
        r = random.Random(seed)
        img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        d = ImageDraw.Draw(img)
        cx = w // 2
        d.polygon([(cx - w * 0.07, h), (cx + w * 0.07, h), (cx + w * 0.025, h * 0.25), (cx - w * 0.025, h * 0.25)], fill=sil)
        for _ in range(branches):
            y = r.uniform(h * 0.2, h * 0.7)
            side = r.choice((-1, 1))
            length = r.uniform(w * 0.2, w * 0.45)
            ex, ey = cx + side * length, y - r.uniform(h * 0.05, h * 0.2)
            d.line((cx, y, ex, ey), fill=sil, width=max(2, int(w * 0.03)))
            d.line((ex, ey, ex + side * length * 0.3, ey - r.uniform(10, 40)), fill=sil, width=max(2, int(w * 0.015)))
        save(img, rel)

    tree("single/environment/decor_tree_a.png", 256, 512, 9, 1)
    tree("single/environment/decor_tree_b.png", 192, 384, 6, 2)

    rocks = Image.new("RGBA", (256, 96), (0, 0, 0, 0))
    d = ImageDraw.Draw(rocks)
    for x0, w, hgt in ((10, 90, 60), (80, 110, 85), (170, 76, 50)):
        d.ellipse((x0, 96 - hgt, x0 + w, 96 + hgt * 0.6), fill=sil)
    save(rocks, "single/environment/decor_rocks.png")

    grass = Image.new("RGBA", (256, 48), (0, 0, 0, 0))
    d = ImageDraw.Draw(grass)
    r = random.Random(3)
    for _ in range(70):
        x = r.uniform(0, 256)
        hgt = r.uniform(10, 46)
        lean = r.uniform(-8, 8)
        d.polygon([(x - 2, 48), (x + 2, 48), (x + lean, 48 - hgt)], fill=sil)
    save(grass, "single/environment/decor_grass.png")

    post = Image.new("RGBA", (96, 320), (0, 0, 0, 0))
    d = ImageDraw.Draw(post)
    d.rectangle((42, 40, 54, 320), fill=sil)
    d.rectangle((30, 40, 80, 50), fill=sil)
    d.line((74, 50, 74, 74), fill=sil, width=3)
    d.rectangle((64, 74, 84, 100), outline=sil, width=4)
    save(post, "single/environment/decor_post.png")

    # Dark tide: opaque on the left, ragged wisps toward the right edge.
    w, h = 256, 1024
    tide = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = tide.load()
    r = random.Random(5)
    phases = [r.uniform(0, math.tau) for _ in range(4)]
    for y in range(h):
        edge = w * 0.62 + sum(a * math.sin(math.tau * k * y / h + p)
                              for (k, a), p in zip(((3, 22), (7, 14), (13, 8), (29, 5)), phases))
        for x in range(w):
            t = (x - (edge - 70)) / 70.0
            a = 1.0 if t <= 0 else max(0.0, 1.0 - t)
            glow = max(0.0, 1.0 - abs(t - 0.35) / 0.45)          # violet fringe on the front
            px[x, y] = (int(5 + 95 * glow), int(3 + 22 * glow), int(10 + 140 * glow), int(255 * a ** 1.4))
    save(tide.filter(ImageFilter.GaussianBlur(2)), "single/enemies/dark_tide_edge.png")


