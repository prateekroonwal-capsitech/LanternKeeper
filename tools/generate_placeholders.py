# ── UI ───────────────────────────────────────────────────────────────────
def rounded(size, radius, fill, outline=None, width=0):
    img = Image.new("RGBA", size, (0, 0, 0, 0))
    ImageDraw.Draw(img).rounded_rectangle((0, 0, size[0] - 1, size[1] - 1), radius=radius,
                                          fill=fill, outline=outline, width=width)
    return img


def circle(size, fill, outline=None, width=0, inset=0):
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ImageDraw.Draw(img).ellipse((inset, inset, size - 1 - inset, size - 1 - inset), fill=fill,
                                outline=outline, width=width)
    return img


def ring(size, thickness, color):
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ImageDraw.Draw(img).ellipse((2, 2, size - 3, size - 3), outline=color, width=thickness)
    return img


def icon_on_circle(size, draw_fn, bg=(10, 12, 20, 150), fg=(230, 230, 240, 230)):
    img = circle(size, bg, outline=(230, 230, 240, 120), width=4, inset=2)
    draw_fn(ImageDraw.Draw(img), size, fg)
    return img


